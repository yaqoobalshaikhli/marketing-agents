"""Queue simulation for the TabeebX family plan (docs/launch/tele-consult-launch-plan.md).

What it does: families request teleconsultations at random, a fixed number of doctors answer
them first come, first served, and we measure how long families wait.

What it cannot do: it creates no data. Usage rates, consultation length and the time-of-day
pattern are SCENARIOS (the research found no Iraqi numbers), so every result is "if the
assumptions held". Rerun it with your own numbers: python3 queue_sim.py > results.md
"""
import heapq
import sys
import numpy as np

DAYS = 30
REPS = 120
SEED = 20261108
SHAPE = 0.5          # gamma shape of per-family usage: 0.5 = heavy tail (a few families use much more)
CV_SERVICE = 0.6     # spread of consultation length

# hour-of-day weights for the "evening-peaked" scenario (an assumption, not data)
EVENING = np.array([1] * 8 + [3] * 10 + [5] * 6, dtype=float)
EVEN = np.ones(24)


def one_rep(rng, families, mean_per_year, minutes, doctors, profile):
    rates = rng.gamma(SHAPE, mean_per_year / SHAPE, size=families)          # consultations per year, per family
    counts = rng.poisson(rates * DAYS / 365.0)
    n = int(counts.sum())
    top = np.sort(counts)[::-1][: max(1, families // 10)].sum() / max(1, n)  # share from the top 10% of families
    if n == 0:
        return dict(util=0.0, mean_wait=0.0, p95=0.0, over5=0.0, over15=0.0, top10=0.0, n=0)
    w = profile / profile.sum()
    day = rng.integers(0, DAYS, size=n)
    hour = rng.choice(24, size=n, p=w)
    arr = (day * 24 + hour + rng.random(n)) * 60.0                          # minutes from the start
    arr.sort()
    sig2 = np.log(1 + CV_SERVICE ** 2)
    svc = rng.lognormal(np.log(minutes) - sig2 / 2, np.sqrt(sig2), size=n)
    free = [0.0] * doctors
    heapq.heapify(free)
    waits = np.empty(n)
    for i in range(n):
        t = heapq.heappop(free)
        start = arr[i] if arr[i] > t else t
        waits[i] = start - arr[i]
        heapq.heappush(free, start + svc[i])
    return dict(util=svc.sum() / (doctors * DAYS * 24 * 60.0), mean_wait=waits.mean(), p95=np.percentile(waits, 95),
                over5=(waits > 5).mean(), over15=(waits > 15).mean(), top10=top, n=n)


def run(families, mean_per_year, minutes, doctors, profile_name, reps=REPS):
    rng = np.random.default_rng(SEED)
    profile = EVENING if profile_name == "evening" else EVEN
    rs = [one_rep(rng, families, mean_per_year, minutes, doctors, profile) for _ in range(reps)]
    f = lambda k: float(np.mean([r[k] for r in rs]))
    return dict(util=f("util"), mean_wait=f("mean_wait"), p95=f("p95"), over5=f("over5"), over15=f("over15"),
                top10=f("top10"), per_month=f("n"))


def row(label, r):
    return (f"| {label} | {r['per_month']:,.0f} | {r['util']*100:.0f}% | {r['mean_wait']:.1f} | {r['p95']:.1f} | "
            f"{r['over5']*100:.1f}% | {r['over15']*100:.1f}% | {r['top10']*100:.0f}% |")


HEAD = ("| Case | Consultations a month | Doctor time used | Mean wait (min) | 95th-percentile wait (min) | "
        "Wait over 5 min | Wait over 15 min | Share from top 10% of families |\n|---|---|---|---|---|---|---|---|")


def main():
    out = []
    p = out.append
    p("# Simulation of the family plan (generated by queue_sim.py)\n")
    p(f"Setup: {REPS} simulated months of {DAYS} days per case. Usage per family is gamma-distributed with shape {SHAPE} "
      "(a heavy tail: a few families use far more than the rest). Consultation length is lognormal with the stated mean and "
      f"a spread (CV) of {CV_SERVICE}. Calls come in an evening-peaked pattern unless stated. Doctors answer first come, first "
      "served; the number of doctors is the number on duty at the same moment, all day and night.\n")
    p("**Every input is a scenario, not data.** The research found no Iraqi usage rate, consultation length or time-of-day pattern.\n")

    p("## 1. 300 families (the simulation you asked for), 15-minute consultations\n")
    p(HEAD)
    for c in (1, 2, 3):
        for mu in (2.4, 8, 24):
            p(row(f"{c} doctor(s) on duty, {mu:g} a family a year", run(300, mu, 15, c, "evening")))
    p("")

    p("## 2. Growing past 300 families (8 consultations a family a year, 15 minutes)\n")
    p(HEAD)
    for c in (1, 2, 3):
        for n in (300, 1000, 2000, 3000, 5000):
            p(row(f"{c} doctor(s), {n:,} families", run(n, 8, 15, c, "evening")))
    p("")

    p("## 3. Stress: heavy use and long consultations at 1,000 families\n")
    p(HEAD)
    for c in (1, 3):
        for mu, m in ((8, 8), (8, 25), (24, 15), (24, 25)):
            p(row(f"{c} doctor(s), {mu} a family a year, {m} min", run(1000, mu, m, c, "evening")))
    p("")

    p("## 4. How many families before the 95th-percentile wait passes 15 minutes (15-minute consultations)\n")
    p("| Doctors on duty | 2.4 a family a year | 8 a family a year | 24 a family a year |\n|---|---|---|---|")
    for c in (1, 2, 3):
        cells = []
        for mu in (2.4, 8, 24):
            lo, hi, best = 100, 60000, None
            while lo <= hi:
                mid = (lo + hi) // 2
                r = run(mid, mu, 15, c, "evening", reps=30)
                if r["p95"] <= 15:
                    best, lo = mid, mid + 1
                else:
                    hi = mid - 1
                lo = max(lo, 100)
            cells.append(f"about {int(round(best, -1)):,}" if best else "under 100")
        p(f"| {c} | " + " | ".join(cells) + " |")
    p("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
